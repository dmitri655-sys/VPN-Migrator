"""Linux/root synthetic migration: real SQLite/WAL, TLS, tar, permissions, lock.

No VPS or real x-ui system service is touched. Systemctl/facts are simulated;
all filesystem paths are redirected to two temporary directories.
"""
import contextlib
import io
import os
from pathlib import Path
import platform
import sqlite3
import stat
import subprocess
import sys
import tempfile
from unittest.mock import patch
import uuid

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from vps_migrator import remote as r


MINIMAL_UNIT = "[Service]\nExecStart=/usr/local/x-ui/x-ui\nEnvironmentFile=/etc/default/x-ui\n"
# Directives of stock 3x-ui x-ui.service.debian and its generated sandbox drop-in.
STOCK_UNIT = ("[Service]\nEnvironmentFile=-/etc/default/x-ui\nEnvironment=\"XRAY_VMESS_AEAD_FORCED=false\"\n"
              "Type=simple\nWorkingDirectory=/usr/local/x-ui/\nExecStart=/usr/local/x-ui/x-ui\n"
              "ExecReload=/bin/kill -USR1 $MAINPID\nRestart=on-failure\nKillMode=mixed\n"
              "ProtectSystem=full\nReadWritePaths=-/etc/x-ui -/usr/local/x-ui -/var/log/x-ui\n")
STOCK_DROPIN = ("# Regenerated by install.sh/update.sh\n[Service]\n"
                "ReadWritePaths=-/etc/x-ui -/var/log/x-ui -/usr/local/x-ui/bin -/usr/local/x-ui\n"
                "ReadWriteDirectories=-/etc/x-ui -/var/log/x-ui -/usr/local/x-ui/bin -/usr/local/x-ui\n"
                "SystemCallFilter=@system-service\nSystemCallErrorNumber=EPERM\n")


def main():
    if sys.platform != "linux" or os.geteuid() != 0:
        raise SystemExit("Run this synthetic smoke test on Linux as root")
    scenario("minimal unit", MINIMAL_UNIT, None)
    scenario("stock 3x-ui unit + sandbox drop-in", STOCK_UNIT, STOCK_DROPIN)
    print("Real WAL snapshot, TLS/OpenSSL, checksums, root:root/0600, flock and rename; systemctl/facts simulated.")


def scenario(title, unit, dropin):
    cert = "/root/cert/sakha-ai.ru"
    real_run = r.run
    operations = []
    with tempfile.TemporaryDirectory(prefix="vps-migrator-smoke-") as folder:
        source, target = (Path(folder) / name for name in ("source", "target"))
        for root in (source, target):
            (root / "var/lib").mkdir(parents=True)

        def write(name, content, mode=0o600):
            p = source / name.lstrip("/")
            p.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
            p.write_text(content)
            p.chmod(mode)

        write(r.UNIT, unit, 0o644)
        if dropin:
            write(r.DROPIN, dropin, 0o644)
            (source / r.DROPIN_DIR.lstrip("/")).chmod(0o755)
        write(r.ENV, "XUI_DB_TYPE=sqlite\nXUI_DB_FOLDER=/etc/x-ui\n")
        write(r.APP + "/x-ui", "synthetic executable; must never run", 0o700)
        write(r.APP + "/bin/xray-linux-amd64", "synthetic executable; must never run", 0o700)
        (source / "etc/x-ui").mkdir(mode=0o700)
        tls = source / cert.lstrip("/")
        tls.mkdir(parents=True, mode=0o700)
        subprocess.run(["openssl", "req", "-x509", "-newkey", "rsa:2048", "-nodes", "-days", "1",
                        "-keyout", str(tls / "key.pem"), "-out", str(tls / "cert.pem"),
                        "-subj", "/CN=sakha-ai.ru"], check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)

        def fake_run(*args, **kwargs):
            if args[0] != "systemctl":
                return real_run(*args, **kwargs)
            operations.append((str(r.ROOT), args))
            if "--property=FragmentPath" in args:
                return r.UNIT if r.path(r.UNIT).is_file() else ""
            if "--property=DropInPaths" in args:
                return r.DROPIN if r.path(r.DROPIN).is_file() else ""
            if "is-active" in args:
                return "active" if r.ROOT == source else "inactive"
            return ""

        def facts():
            return {"os": "ubuntu", "arch": platform.machine(), "libc": ["glibc", "2.36"],
                    "machine_id": "source" if r.ROOT == source else "target",
                    "free_bytes": 10 * 1024**3, "systemd": 252, "listeners": {"tcp": [], "udp": []}}

        with contextlib.closing(sqlite3.connect(source / "etc/x-ui/x-ui.db")) as connection:
            connection.executescript('PRAGMA journal_mode=WAL; PRAGMA wal_autocheckpoint=0; '
                'CREATE TABLE inbounds(id INTEGER, settings TEXT); CREATE TABLE users(id INTEGER); '
                'CREATE TABLE settings(key TEXT,value TEXT); CREATE TABLE nodes(id INTEGER); '
                'INSERT INTO inbounds VALUES(1,\'{"clients":[{"id":"synthetic-secret"}]}\'); '
                'INSERT INTO users VALUES(1); INSERT INTO settings VALUES(\'key\',\'secret\');')
            connection.commit()
            job = str(uuid.uuid4())
            with patch.object(r, "ROOT", source), patch.object(r, "run", fake_run), patch.object(r, "facts", facts):
                source_info = r.discover({"cert": cert})
                exported = r.dispatch("export", {"job": job, "cert": cert})
                archive = (r.job_path(job) / "payload.tar").read_bytes()
                connection.execute("INSERT INTO users VALUES(2)")
                connection.commit()
                r.ROOT = target
                stdin = type("Input", (), {"buffer": io.BytesIO(archive)})()
                with patch.object(sys, "stdin", stdin):
                    state = r.dispatch("stage", {"job": job, "cert": cert, "source": source_info,
                                                  "size": exported["size"], "sha256": exported["sha256"]})
                assert state["db_summary"] == {"inbounds": 1, "users": 1, "settings": 1, "clients": 1, "nodes": 0}
                assert not r.path(r.APP).exists(), "Staging must not install files"
                r.dispatch("commit", {"job": job})
                for name in (r.ENV, r.DBDIR + "/x-ui.db", cert + "/key.pem"):
                    assert stat.S_IMODE(r.path(name).stat().st_mode) == 0o600
                    assert (r.path(name).stat().st_uid, r.path(name).stat().st_gid) == (0, 0)
                assert os.access(r.path(r.APP + "/x-ui"), os.X_OK)
                if dropin:
                    assert r.path(r.DROPIN).read_text() == dropin
                    assert stat.S_IMODE(r.path(r.DROPIN).stat().st_mode) == 0o644
                    assert (r.path(r.DROPIN).stat().st_uid, r.path(r.DROPIN).stat().st_gid) == (0, 0)
                assert r.database_summary(r.path(r.DBDIR + "/x-ui.db"))["users"] == 1
                with contextlib.closing(sqlite3.connect(r.path(r.DBDIR + "/x-ui.db"))) as changed:
                    changed.execute("INSERT INTO users VALUES(3)")
                    changed.commit()
                r.dispatch("rollback", {"job": job})
                assert all(not r.path(name).exists() for name in r.roots(cert, r.ENV, bool(dropin)))
                preserved = r.job_path(job) / "stage/etc/x-ui/x-ui.db"
                assert r.database_summary(preserved)["users"] == 2
                assert not any(root == str(source) and args[1] in ("stop", "start") for root, args in operations)
                assert not any(args[1] == "start" for _, args in operations), "Commit must not start services"
    print("Linux synthetic export → stage → commit → rollback (" + title + "): PASS")


if __name__ == "__main__":
    main()
