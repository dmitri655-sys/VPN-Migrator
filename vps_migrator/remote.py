ROOT = Path("/")
BASE = "/var/lib/vps-migrator"
APP = "/usr/local/x-ui"
DBDIR = "/etc/x-ui"
UNIT = "/etc/systemd/system/x-ui.service"
ENV = "/etc/default/x-ui"
# Generated by stock 3x-ui install.sh/update.sh; the only supported drop-in.
DROPIN_DIR = "/etc/systemd/system/x-ui.service.d"
DROPIN = DROPIN_DIR + "/10-xui-sandbox.conf"
# Exact lines of the stock unit (x-ui.service.debian); anything else is refused.
STOCK_ENVIRONMENT = ('"XRAY_VMESS_AEAD_FORCED=false"', "XRAY_VMESS_AEAD_FORCED=false")
STOCK_RELOAD = ("/bin/kill -USR1 $MAINPID", "/usr/bin/kill -USR1 $MAINPID")
DROPIN_PATHS = ("-/etc/x-ui", "-/var/log/x-ui", "-/usr/local/x-ui", "-/usr/local/x-ui/bin")
PORTS = {"tcp": [443, 8443, 36282, 2096, 58291], "udp": [443, 46331]}
LIMIT = 8 * 1024**3
MAX_FILES = 100000


def require(condition, message):
    if not condition:
        raise ValueError(message)


def path(name):
    return ROOT / name.lstrip("/")


def no_links(p):
    # Also reject linked parents, not just the final member.
    require(not any(q.is_symlink() for q in [p, *p.parents]), "Символические ссылки не поддерживаются: " + str(p))


def cert_path(value):
    require(bool(re.fullmatch(r"/root/cert/[a-zA-Z0-9][a-zA-Z0-9.-]{0,252}", value)),
            "TLS каталог должен иметь вид /root/cert/domain.tld")
    require(value.rsplit("/", 1)[1] not in (".", ".."), "Недопустимый TLS каталог")
    return value


def job_path(value):
    require(str(uuid.UUID(value)) == value, "Некорректный UUID")
    return path(BASE) / value


def run(*args, ok=True):
    result = subprocess.run(args, stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=45)
    if ok and result.returncode:
        # Never print service logs/config or command stdout: they may contain secrets.
        raise RuntimeError("Не удалось выполнить " + args[0] + " (вывод скрыт во избежание утечки секретов)")
    return result.stdout.decode(errors="replace").strip()


def system(action):
    return run("systemctl", action, "x-ui.service")


def sha(p):
    h = hashlib.sha256()
    with p.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def save(p, data):
    temp = p.with_suffix(".tmp")
    with temp.open("w", encoding="utf-8") as stream:
        json.dump(data, stream)
        stream.flush()
        os.fsync(stream.fileno())
    os.chmod(temp, 0o600)
    os.replace(temp, p)
    sync_dir(p.parent)


def sync_dir(p):
    if os.name == "posix":
        fd = os.open(p, os.O_RDONLY | os.O_DIRECTORY)
        try:
            os.fsync(fd)
        finally:
            os.close(fd)


def read(p):
    return json.loads(p.read_text(encoding="utf-8"))


def inspect_tree(p):
    no_links(p)
    require(p.exists(), "Отсутствует " + str(p))
    members = [p] + (sorted(p.rglob("*")) if p.is_dir() else [])
    require(len(members) <= MAX_FILES, "Слишком много файлов")
    for item in members:
        s = item.lstat()
        require(stat.S_ISREG(s.st_mode) or stat.S_ISDIR(s.st_mode), "Только обычные файлы/каталоги: " + str(item))
        require(s.st_uid == 0 and s.st_gid == 0, "MVP поддерживает только root:root: " + str(item))
        require(not s.st_mode & 0o7022, "Запрещены special bits и запись group/other: " + str(item))
    return members


def unit_source():
    fragment = run("systemctl", "show", "x-ui.service", "--property=FragmentPath", "--value")
    require(fragment in (UNIT, "/usr/lib/systemd/system/x-ui.service", "/lib/systemd/system/x-ui.service"),
            "Неизвестное расположение unit x-ui")
    # /lib itself may be a standard merged-/usr symlink; resolve ONLY system unit here.
    unit = path(fragment).resolve()
    inspect_tree(unit)
    dropin_source()
    validate_unit(unit)
    return unit


def dropin_source():
    """None or the stock sandbox drop-in; any other drop-in is refused."""
    found = run("systemctl", "show", "x-ui.service", "--property=DropInPaths", "--value").split()
    if not found:
        return None
    require(found == [DROPIN], "Поддерживается только стандартный drop-in " + DROPIN)
    folder = path(DROPIN_DIR)
    members = inspect_tree(folder)
    require(sorted(members) == sorted([folder, path(DROPIN)]),
            "В каталоге drop-in допускается только 10-xui-sandbox.conf")
    result = validate_dropin(path(DROPIN))
    return {"path": DROPIN_DIR, "syscall_filter": result["syscall_filter"]}


def validate_dropin(p):
    """Stock 10-xui-sandbox.conf: only writable-path list and syscall filter."""
    text = p.read_text(encoding="utf-8")
    require(len(text) < 65536 and "\\\n" not in text, "Сложный drop-in не поддерживается")
    syscall_filter = False
    section = None
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith(("#", ";")):
            continue
        if line.startswith("["):
            require(line == "[Service]" and section is None, "Drop-in: допускается только секция [Service]")
            section = line
            continue
        require(section == "[Service]" and "=" in line, "Drop-in: неподдерживаемая строка")
        key, value = (part.strip() for part in line.split("=", 1))
        if key in ("ReadWritePaths", "ReadWriteDirectories"):
            words = value.split()
            require(words and set(words) <= set(DROPIN_PATHS), "Drop-in: неподдерживаемые пути записи")
        elif key == "SystemCallFilter":
            require(value == "@system-service", "Drop-in: нестандартный SystemCallFilter")
            syscall_filter = True
        elif key == "SystemCallErrorNumber":
            require(value == "EPERM", "Drop-in: нестандартный SystemCallErrorNumber")
        else:
            raise ValueError("Drop-in: неподдерживаемая директива " + key)
    return {"syscall_filter": syscall_filter}


def validate_unit(p):
    text = p.read_text()
    require(len(text) < 65536 and "\\\n" not in text, "Сложный unit не поддерживается")
    pairs = [line.strip().split("=", 1) for line in text.splitlines()
             if "=" in line and not line.lstrip().startswith(("#", ";"))]
    execs = [(k.strip(), v.strip()) for k, v in pairs if k.strip().startswith("Exec")]
    starts = [e for e in execs if e[0] == "ExecStart"]
    reloads = [e for e in execs if e[0] == "ExecReload"]
    require(starts == [("ExecStart", "/usr/local/x-ui/x-ui")] and len(starts) + len(reloads) == len(execs)
            and len(reloads) <= 1 and all(v in STOCK_RELOAD for _, v in reloads),
            "Требуется единственный ExecStart=/usr/local/x-ui/x-ui без hooks/аргументов "
            "(допустим только стандартный ExecReload 3x-ui)")
    for k, v in pairs:
        if k.strip() == "KillMode":
            # mixed: SIGTERM to the main process, then SIGKILL to the whole cgroup.
            require(v.strip() in ("control-group", "mixed"),
                    "Для безопасного stop нужен KillMode=control-group или mixed")
        if k.strip() == "Environment":
            require(v.strip() in STOCK_ENVIRONMENT,
                    "Поддерживается только стандартный Environment 3x-ui (значение скрыто)")
        if k.strip() == "SendSIGKILL":
            require(v.strip().lower() in ("yes", "true", "1"), "Для безопасного stop нужен SendSIGKILL=yes")
        if k.strip() in ("User", "Group"):
            require(v.strip() == "root", "Поддерживается только service от root")
        require(k.strip() not in ("RootDirectory", "RootImage", "BindPaths", "BindReadOnlyPaths"),
                "Внешние зависимости unit не поддерживаются")
    unit_environment(p)


def unit_environment(p):
    values = [line.split("=", 1)[1].strip() for line in p.read_text().splitlines()
              if "=" in line and line.split("=", 1)[0].strip() == "EnvironmentFile"]
    require(len(values) <= 1, "Поддерживается один стандартный EnvironmentFile")
    if not values:
        return None, False
    require(values[0] in (ENV, "-" + ENV), "Поддерживается только EnvironmentFile=/etc/default/x-ui")
    return ENV, values[0].startswith("-")


def read_environment(p):
    require(p.stat().st_size <= 65536, "Слишком большой env-файл")
    result = {}
    for line in p.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        require("=" in line and not any(c in line for c in ("$", "`", "\\", "\x00")),
                "Неподдерживаемый синтаксис env-файла (значения скрыты)")
        key, raw = line.split("=", 1)
        key = key.strip()
        require(key in ("XUI_DB_TYPE", "XUI_DB_FOLDER", "XUI_BIN_FOLDER", "XUI_LOG_LEVEL"),
                "Неподдерживаемая переменная env-файла (значение скрыто)")
        try:
            words = shlex.split(raw, comments=False)
        except ValueError:
            raise ValueError("Неподдерживаемый синтаксис env-файла (значения скрыты)") from None
        require(len(words) == 1 and key not in result, "Пустая/повторяющаяся переменная env-файла")
        value = words[0]
        valid = {"XUI_DB_TYPE": ("sqlite",), "XUI_DB_FOLDER": (DBDIR,),
                 "XUI_BIN_FOLDER": (APP + "/bin",),
                 "XUI_LOG_LEVEL": ("debug", "info", "notice", "warning", "warn", "error")}
        require(value in valid[key], "Неподдерживаемое значение env: только SQLite и стандартные пути (значение скрыто)")
        result[key] = value
    return result


def source_environment(unit):
    name, optional = unit_environment(unit)
    if name is None:
        return None
    p = path(name)
    no_links(p)
    if not p.exists():
        require(optional, "Отсутствует обязательный /etc/default/x-ui")
        return None
    require(p.is_file(), "Env должен быть обычным файлом")
    inspect_tree(p)
    read_environment(p)
    return name


def systemd_version():
    match = re.match(r"systemd (\d+)", run("systemctl", "--version"))
    return int(match.group(1)) if match else 0


def listening():
    result = {"tcp": [], "udp": []}
    for proto, flag in (("tcp", "-lntH"), ("udp", "-lnuH")):
        for line in run("ss", flag).splitlines():
            cols = line.split()
            # ss without -p: State Recv-Q Send-Q LocalAddress:Port PeerAddress:Port
            if len(cols) >= 5:
                value = cols[3].rsplit(":", 1)[-1]
                if value.isdigit():
                    result[proto].append(int(value))
        result[proto] = sorted(set(result[proto]))
    return result


def facts():
    release = {}
    for line in path("/etc/os-release").read_text().splitlines():
        if "=" in line:
            key, value = line.split("=", 1)
            release[key] = value.strip('"')
    require(release.get("ID") in ("ubuntu", "debian"), "Только Ubuntu/Debian")
    require(path("/run/systemd/system").is_dir(), "Требуется systemd")
    for tool in ("systemctl", "ss", "openssl", "ldd"):
        require(shutil.which(tool), "Установите системную команду " + tool)
    return {"os": release["ID"], "version": release.get("VERSION_ID"),
            "arch": platform.machine(), "libc": platform.libc_ver(),
            "machine_id": path("/etc/machine-id").read_text().strip(),
            "systemd": systemd_version(),
            "listeners": listening(), "free_bytes": shutil.disk_usage(path("/var/lib")).free}


def discover(args):
    cert = cert_path(args.get("cert", "/root/cert/sakha-ai.ru"))
    data = facts()
    unit = unit_source()
    environment = source_environment(unit)
    dropin = dropin_source()
    members = []
    for name in (DBDIR, APP, cert):
        members += inspect_tree(path(name))
    if environment:
        members += inspect_tree(path(environment))
    if dropin:
        members += inspect_tree(path(DROPIN_DIR))
    require(path(DBDIR + "/x-ui.db").is_file(), "Нет базы x-ui.db")
    require(os.access(path(APP + "/x-ui"), os.X_OK), "Нет исполняемого x-ui")
    data.update({"cert": cert, "unit": str(unit), "environment": environment, "dropin": dropin,
                 "service": run("systemctl", "is-active", "x-ui.service", ok=False),
                 "bytes": sum(p.stat().st_size for p in members if p.is_file()),
                 "expected_ports": PORTS,
                 "warnings": ["AWG2 Docker не переносится", "Bind IP и внешние пути требуют проверки",
                              "Данные после SQLite snapshot не синхронизируются",
                              "Не обновляйте установку и сертификаты во время копирования"]})
    return data


def fresh(cert):
    for folder in ("/etc/systemd/system", "/run/systemd/system", "/usr/lib/systemd/system",
                   "/lib/systemd/system", "/etc/systemd/system.control", "/run/systemd/system.control"):
        for suffix in ("x-ui.service.d", "service.d", "x-.service.d",
                       "x-ui.socket", "x-ui.path", "x-ui.timer"):
            p = path(folder) / suffix
            require(not p.exists() and not p.is_symlink(), "Неподдерживаемая systemd зависимость на цели: " + str(p))
    for folder in ("/etc/systemd/system", "/run/systemd/system"):
        require(not list(path(folder).glob("*.wants/x-ui.service")) and
                not list(path(folder).glob("*.requires/x-ui.service")),
                "На цели уже есть ссылка автозапуска x-ui")
    for name in (DBDIR, APP, cert, UNIT, ENV, "/usr/lib/systemd/system/x-ui.service",
                 "/lib/systemd/system/x-ui.service", "/etc/systemd/system/x-ui.service.d",
                 "/run/systemd/system/x-ui.service", "/run/systemd/system/x-ui.service.d"):
        p = path(name)
        # Don't reject normal /lib -> /usr/lib here; nothing is written there.
        require(not p.exists() and not p.is_symlink(), "Цель не чистая: " + name)
    require(not run("systemctl", "show", "x-ui.service", "--property=FragmentPath", "--value"),
            "На цели уже есть unit x-ui")
    require(not run("systemctl", "show", "x-ui.service", "--property=DropInPaths", "--value"),
            "На цели уже есть systemd drop-ins x-ui")
    require(run("systemctl", "is-active", "x-ui.service", ok=False) != "active", "x-ui уже запущен")
    for name in (DBDIR, APP, cert, UNIT, ENV):
        no_links(path(name))


def preflight(args):
    cert = cert_path(args["cert"])
    source = args["source"]
    data = facts()
    require(source["machine_id"] != data["machine_id"], "Одна машина или клонированный machine-id")
    require(source["arch"] == data["arch"], "Разные архитектуры CPU")
    require(source["libc"][0] == data["libc"][0] == "glibc", "Требуется glibc")
    version = lambda s: tuple(int(x) for x in s.split("."))
    require(version(data["libc"][1]) >= version(source["libc"][1]), "На цели более старая glibc")
    fresh(cert)
    if (source.get("dropin") or {}).get("syscall_filter"):
        require(data.get("systemd", 0) >= 239,
                "Drop-in источника использует SystemCallFilter: на цели нужен systemd 239+")
    for proto, ports in PORTS.items():
        require(not set(ports).intersection(data["listeners"][proto]), "На цели занят ожидаемый порт " + proto)
    require(data["free_bytes"] > source["bytes"] * 3 + 256 * 1024**2, "Недостаточно места для staging")
    devices = {path("/var/lib").stat().st_dev}
    for name in (DBDIR, APP, cert, UNIT, ENV):
        parent = path(name).parent
        while not parent.exists():
            parent = parent.parent
        devices.add(parent.stat().st_dev)
    require(len(devices) == 1, "MVP требует staging и конечные пути на одной файловой системе")
    return data


def backup_sqlite(source, target):
    deadline = time.monotonic() + 120
    def progress(status, remaining, total):
        require(time.monotonic() < deadline, "SQLite backup: превышено 120 секунд")
    # No immutable=1: WAL must be included. Read-only does not checkpoint source.
    with contextlib.closing(sqlite3.connect(source.as_uri() + "?mode=ro", uri=True)) as src:
        with contextlib.closing(sqlite3.connect(target)) as dst:
            src.backup(dst, pages=256, progress=progress, sleep=0.1)
            require(dst.execute("PRAGMA integrity_check").fetchall() == [("ok",)], "SQLite integrity_check не пройден")
            dst.execute("PRAGMA journal_mode=DELETE")
    os.chmod(target, 0o600)


def roots(cert, environment=None, dropin=False):
    require(environment in (None, ENV), "Недопустимый env-путь")
    result = [DBDIR.lstrip("/"), APP.lstrip("/"), cert.lstrip("/"), UNIT.lstrip("/")]
    return (result + ([ENV.lstrip("/")] if environment else []) +
            ([DROPIN_DIR.lstrip("/")] if dropin else []))


def database_summary(db):
    with contextlib.closing(sqlite3.connect(db.as_uri() + "?mode=ro", uri=True)) as conn:
        tables = {row[0] for row in conn.execute("SELECT name FROM sqlite_master WHERE type='table'")}
        require({"inbounds", "users", "settings"} <= tables, "Не найдены обязательные таблицы 3x-ui")
        counts = {name: conn.execute("SELECT count(*) FROM " + name).fetchone()[0]
                  for name in ("inbounds", "users", "settings")}
        nodes = conn.execute("SELECT count(*) FROM nodes").fetchone()[0] if "nodes" in tables else 0
        require(nodes == 0, "Обнаружены внешние узлы: multi-node перенос не поддерживается")
        columns = {row[1] for row in conn.execute("PRAGMA table_info(inbounds)")}
        require("settings" in columns, "Не найдено поле settings в inbounds")
        clients = 0
        for (text,) in conn.execute("SELECT settings FROM inbounds"):
            try:
                settings = json.loads(text)
            except (ValueError, TypeError):
                raise ValueError("Некорректный JSON настроек inbound (содержимое скрыто)") from None
            require(isinstance(settings, dict) and isinstance(settings.get("clients", []), list),
                    "Некорректный список клиентов inbound (содержимое скрыто)")
            clients += len(settings.get("clients", []))
        return dict(counts, clients=clients, nodes=nodes)


def verify_summary(db, expected):
    require(database_summary(db) == expected, "Количество данных не совпадает со снимком")


def export(args):
    cert = cert_path(args["cert"])
    info = discover({"cert": cert})
    job = job_path(args["job"])
    job.mkdir(mode=0o700)
    snapshot = job / "snapshot.db"
    backup_sqlite(path(DBDIR + "/x-ui.db"), snapshot)
    summary = database_summary(snapshot)
    records = {}
    with tarfile.open(job / "payload.tar", "w", dereference=True) as tar:
        entries = []
        for name in (DBDIR, APP, cert):
            entries += [(p, p.relative_to(ROOT).as_posix()) for p in inspect_tree(path(name))]
        entries.append((unit_source(), UNIT.lstrip("/")))
        if info.get("environment"):
            entries.append((path(ENV), ENV.lstrip("/")))
        if info.get("dropin"):
            entries += [(p, p.relative_to(ROOT).as_posix()) for p in inspect_tree(path(DROPIN_DIR))]
        total = 0
        for original, name in entries:
            if name in ("etc/x-ui/x-ui.db-wal", "etc/x-ui/x-ui.db-shm", "etc/x-ui/x-ui.db-journal"):
                continue
            p = snapshot if name == "etc/x-ui/x-ui.db" else original
            meta = tar.gettarinfo(str(p), arcname=name)
            # gettarinfo keeps S_IFREG/S_IFDIR; tar serializes only permission bits.
            meta.mode = stat.S_IMODE(meta.mode)
            meta.uid = meta.gid = 0
            meta.uname = meta.gname = "root"
            # TLS keys and DB/configs never need world read. Preserve executable bits.
            if name.startswith(("root/cert/", "etc/x-ui")) or name == ENV.lstrip("/"):
                meta.mode = 0o700 if p.is_dir() else 0o600
            record = {"mode": meta.mode, "dir": p.is_dir(), "size": meta.size}
            if p.is_file():
                record["sha256"] = sha(p)
                total += meta.size
                require(total <= LIMIT, "Архив превышает 8 GiB")
                with p.open("rb") as stream:
                    tar.addfile(meta, stream)
                require(record["sha256"] == sha(p), "Файл изменился при копировании; повторите backup")
            else:
                tar.addfile(meta)
            records[name] = record
        manifest = json.dumps({"schema": 2, "cert": cert, "source": info, "files": records,
                               "environment": info.get("environment"), "dropin": bool(info.get("dropin")),
                               "db_summary": summary}).encode()
        require(len(manifest) <= 16 * 1024**2, "Слишком большой manifest")
        item = tarfile.TarInfo("manifest.json")
        item.size = len(manifest)
        item.mode = 0o600
        tar.addfile(item, io.BytesIO(manifest))
    archive = job / "payload.tar"
    os.chmod(archive, 0o600)
    save(job / "export.json", {"export": True})
    return {"sha256": sha(archive), "size": archive.stat().st_size, "db_summary": summary}


def allowed(name, cert, environment=None, dropin=False):
    p = PurePosixPath(name)
    require(not p.is_absolute() and ".." not in p.parts and p.as_posix() == name,
            "Небезопасное имя в архиве")
    if dropin and name == DROPIN.lstrip("/"):
        return True
    # Single-file roots and the drop-in folder have no other allowed children.
    closed = (UNIT.lstrip("/"), ENV.lstrip("/"), DROPIN_DIR.lstrip("/"))
    return any(name == base or (base not in closed and name.startswith(base + "/"))
               for base in roots(cert, environment, dropin))


def unpack(archive, destination, cert, environment=None, dropin=False):
    # Entire index validated BEFORE any write. Never use extract/extractall.
    with tarfile.open(archive, "r:") as tar:
        members = []
        for member in tar:
            members.append(member)
            require(len(members) <= MAX_FILES, "Слишком много записей")
        names = [m.name for m in members]
        require(len(names) == len(set(names)), "Дублирующиеся записи")
        require(names.count("manifest.json") == 1, "Нет manifest")
        manifest_item = tar.getmember("manifest.json")
        require(manifest_item.isfile() and manifest_item.size <= 16 * 1024**2, "Неверный manifest")
        manifest = json.load(tar.extractfile(manifest_item))
        require(manifest["schema"] in (1, 2) and manifest["cert"] == cert and
                manifest.get("environment") == environment and
                bool(manifest.get("dropin")) == dropin, "Несовместимый manifest")
        require(set(names) - {"manifest.json"} == set(manifest["files"]), "Состав архива не совпадает с manifest")
        total = 0
        for m in members:
            if m.name == "manifest.json":
                continue
            require(allowed(m.name, cert, environment, dropin), "Путь вне разрешённого списка")
            require(m.isdir() or m.isfile(), "Ссылки/устройства запрещены")
            require(not m.issparse(), "Sparse файлы запрещены")
            require(m.uid == m.gid == 0 and not m.mode & 0o7022, "Недопустимые права/владелец")
            r = manifest["files"][m.name]
            require((m.isdir(), m.size, m.mode) == (r["dir"], r["size"], r["mode"]), "Metadata не совпадает")
            total += m.size
        require(total <= LIMIT, "Слишком большой архив")
        for base in roots(cert, environment, dropin):
            require(base in names, "Нет обязательного корня " + base)
        # Create dirs before files; chmod only after extraction for read-only dirs.
        for m in sorted(members, key=lambda x: (not x.isdir(), len(x.name))):
            if m.name == "manifest.json":
                continue
            target = destination / m.name
            target.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
            no_links(target)
            if m.isdir():
                target.mkdir(exist_ok=True, mode=0o700)
            else:
                with target.open("xb") as out, tar.extractfile(m) as inp:
                    shutil.copyfileobj(inp, out, 1024 * 1024)
                    out.flush()
                    os.fsync(out.fileno())
                require(sha(target) == manifest["files"][m.name]["sha256"], "Checksum файла не совпадает")
        for m in members:
            if m.name != "manifest.json":
                os.chmod(destination / m.name, m.mode)
                os.chown(destination / m.name, 0, 0)
    return manifest


def validate_payload(stage, cert, environment=None, dropin=False):
    db = stage / "etc/x-ui/x-ui.db"
    with contextlib.closing(sqlite3.connect(db.as_uri() + "?mode=ro", uri=True)) as connection:
        require(connection.execute("PRAGMA integrity_check").fetchall() == [("ok",)], "База повреждена")
    validate_unit(stage / UNIT.lstrip("/"))
    referenced, optional = unit_environment(stage / UNIT.lstrip("/"))
    require(environment == referenced or (environment is None and optional), "Env-файл не совпадает с unit")
    if environment:
        read_environment(stage / environment.lstrip("/"))
    folder = stage / DROPIN_DIR.lstrip("/")
    if dropin:
        require(sorted(folder.iterdir()) == [stage / DROPIN.lstrip("/")],
                "В каталоге drop-in допускается только 10-xui-sandbox.conf")
        validate_dropin(stage / DROPIN.lstrip("/"))
    else:
        require(not folder.exists(), "Drop-in не указан в manifest")
    require(os.access(stage / "usr/local/x-ui/x-ui", os.X_OK), "x-ui не исполняемый")
    binaries = list((stage / "usr/local/x-ui/bin").glob("xray*"))
    require(any(p.is_file() and os.access(p, os.X_OK) for p in binaries), "Не найден исполняемый Xray")
    # Parse public parts only; private keys never appear in stdout.
    certs, keys = set(), set()
    for p in (stage / cert.lstrip("/")).rglob("*"):
        if not p.is_file():
            continue
        pub = run("openssl", "x509", "-in", str(p), "-pubkey", "-noout", ok=False)
        if pub.startswith("-----BEGIN PUBLIC KEY-----"):
            run("openssl", "x509", "-in", str(p), "-checkend", "0", "-noout")
            certs.add(pub)
        # -passin pass: refuses encrypted keys instead of hanging for input.
        key = run("openssl", "pkey", "-in", str(p), "-pubout", "-passin", "pass:", ok=False)
        if key.startswith("-----BEGIN PUBLIC KEY-----"):
            keys.add(key)
    require(bool(certs & keys), "Нет действующей PEM пары сертификат/ключ TLS")


def stage(args):
    cert = cert_path(args["cert"])
    preflight(args)
    job = job_path(args["job"])
    job.mkdir(mode=0o700)
    archive = job / "payload.tar"
    expected = args["size"]
    require(isinstance(expected, int) and 0 < expected <= LIMIT + 128 * 1024**2, "Размер архива вне лимита")
    remaining = expected
    with archive.open("xb") as out:
        while remaining:
            block = sys.stdin.buffer.read(min(1024 * 1024, remaining))
            require(block, "Передача оборвалась")
            out.write(block)
            remaining -= len(block)
        require(not sys.stdin.buffer.read(1), "Лишние байты в передаче")
    require(sha(archive) == args["sha256"], "Checksum архива не совпадает")
    staging = job / "stage"
    staging.mkdir(mode=0o700)
    environment = args["source"].get("environment")
    dropin = bool(args["source"].get("dropin"))
    manifest = unpack(archive, staging, cert, environment, dropin)
    require(manifest["source"]["machine_id"] == args["source"]["machine_id"], "Источник изменился")
    require(manifest.get("schema") == 2 and isinstance(manifest.get("db_summary"), dict),
            "Нужен новый backup версии 0.2 с проверкой данных")
    validate_payload(staging, cert, environment, dropin)
    verify_summary(staging / "etc/x-ui/x-ui.db", manifest["db_summary"])
    save(job / "manifest.json", manifest)
    state = {"job": args["job"], "state": "staged", "cert": cert, "environment": environment,
             "dropin": dropin,
             "db_summary": manifest["db_summary"],
             "intent": [], "source": args["source"]}
    save(job / "state.json", state)
    return state


def verify_files(stage, manifest):
    for name, record in manifest["files"].items():
        p = stage / name
        no_links(p)
        require(p.exists() and p.is_dir() == record["dir"], "Staging изменён")
        require(stat.S_IMODE(p.stat().st_mode) == record["mode"], "Права staging изменены")
        if not record["dir"]:
            require(sha(p) == record["sha256"], "Staging checksum изменён")


def rollback_job(job, state):
    # State written before stop so interrupted rollback is retryable.
    state["state"] = "rolling-back"
    save(job / "state.json", state)
    if UNIT.lstrip("/") in state["intent"] and path(UNIT).exists():
        system("stop")
        require(run("systemctl", "is-active", "x-ui.service", ok=False) != "active", "Не удалось остановить x-ui")
    # Do not delete data: move everything back to staging, including new writes.
    for name in reversed(state["intent"]):
        target, original = path("/" + name), job / "stage" / name
        no_links(target)
        if target.exists():
            require(not original.exists(), "Конфликт rollback: оба пути существуют")
            os.rename(target, original)
            sync_dir(target.parent)
            sync_dir(original.parent)
    run("systemctl", "daemon-reload")
    state["state"] = "rolled-back"
    save(job / "state.json", state)
    return state


def commit(job, state):
    require(state["state"] == "staged", "Для commit требуется staged")
    preflight({"cert": state["cert"], "source": state["source"]})
    verify_files(job / "stage", read(job / "manifest.json"))
    validate_payload(job / "stage", state["cert"], state.get("environment"), state.get("dropin", False))
    manifest = read(job / "manifest.json")
    if "db_summary" in manifest:
        verify_summary(job / "stage/etc/x-ui/x-ui.db", manifest["db_summary"])
    state["state"] = "committing"
    save(job / "state.json", state)
    try:
        for name in roots(state["cert"], state.get("environment"), state.get("dropin", False)):
            target = path("/" + name)
            no_links(target)
            require(not target.exists(), "Конечный путь уже существует")
            target.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
            state["intent"].append(name)
            save(job / "state.json", state)
            os.rename(job / "stage" / name, target)
            sync_dir(target.parent)
            sync_dir((job / "stage" / name).parent)
        run("systemctl", "daemon-reload")
        state["state"] = "committed"
        save(job / "state.json", state)
    except Exception:
        rollback_job(job, state)
        raise
    return state


def health():
    active = run("systemctl", "is-active", "x-ui.service", ok=False) == "active"
    ports = listening()
    missing = {proto: sorted(set(wanted) - set(ports[proto])) for proto, wanted in PORTS.items()}
    return {"ok": active and not any(missing.values()), "service_active": active,
            "missing_listeners": missing,
            "scope": "Локальные сокеты; внешний доступ, TLS/SNI, Reality и UDP handshake проверяются клиентами"}


def activate(job, state):
    require(state["state"] == "committed", "Для запуска требуется committed")
    require(run("systemctl", "is-active", "x-ui.service", ok=False) != "active", "x-ui уже запущен вручную")
    ports = listening()
    for proto, wanted in PORTS.items():
        require(not set(wanted).intersection(ports[proto]), "Порт занят перед запуском: " + proto)
    state["state"] = "activating"
    save(job / "state.json", state)
    try:
        system("start")
        deadline = time.monotonic() + 25
        while True:
            result = health()
            if result["ok"] or time.monotonic() >= deadline:
                break
            time.sleep(1)
        require(result["ok"], "Health check не пройден; выполняется rollback")
        state["state"] = "active"
        save(job / "state.json", state)
        return {"state": state, "health": result, "boot": "Автозапуск не включён; см. README"}
    except Exception:
        rollback_job(job, state)
        raise


def discard(job):
    require(job.is_dir(), "Задание не найдено")
    if (job / "state.json").exists():
        require(read(job / "state.json")["state"] in ("staged", "rolled-back"),
                "Сначала rollback; активные/незавершённые установки удалять нельзя")
    shutil.rmtree(job)
    sync_dir(job.parent)
    return {"discarded": job.name}


def dispatch(action, args):
    require(os.geteuid() == 0, "SSH пользователь должен быть root")
    os.umask(0o077)
    if action == "discover":
        return discover(args)
    if action == "preflight":
        return preflight(args)
    # All mutations serialized on each server. No lock file in dry-run.
    import fcntl
    base = path(BASE)
    no_links(base)
    base.mkdir(mode=0o700, parents=True, exist_ok=True)
    require(base.stat().st_uid == base.stat().st_gid == 0 and stat.S_IMODE(base.stat().st_mode) == 0o700,
            "Рабочий каталог должен быть root:root 0700")
    with (base / "lock").open("a") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        job = job_path(args["job"])
        no_links(job)
        if action == "export":
            require(not job.exists(), "UUID задания уже существует")
            try:
                return export(args)
            except Exception:
                if job.exists():
                    shutil.rmtree(job)
                raise
        if action == "download":
            require(read(job / "export.json")["export"], "Не export job")
            with (job / "payload.tar").open("rb") as stream:
                shutil.copyfileobj(stream, sys.stdout.buffer, 1024 * 1024)
            return None
        if action == "cleanup-export":
            require(read(job / "export.json")["export"], "Не export job")
            shutil.rmtree(job)
            return {"cleaned": True}
        if action == "stage":
            return stage(args)
        if action == "status" and not (job / "state.json").exists():
            require(job.is_dir(), "Задание не найдено")
            return {"job": args["job"], "state": "incomplete-staging-or-export",
                    "hint": "Можно discard, затем повторить migrate с новым UUID"}
        if action == "discard":
            return discard(job)
        state = read(job / "state.json")
        if action == "status":
            return state
        if action == "health":
            return health()
        if action == "commit":
            return commit(job, state)
        if action == "activate":
            return activate(job, state)
        if action == "rollback":
            require(state["state"] in ("committing", "committed", "activating", "active", "rolling-back"),
                    "Нет установленного задания для rollback")
            return rollback_job(job, state)
        raise ValueError("Неизвестная операция")


if __name__ == "__main__":
    try:
        action, arguments = json.loads(base64.b64decode(sys.argv[1]))
        result = dispatch(action, arguments)
        if result is not None:
            print(json.dumps(result, ensure_ascii=True))
    except Exception as error:
        # Only our own controlled messages. Raw parser/OS exceptions can expose data.
        if isinstance(error, (ValueError, RuntimeError)) and error.__class__ in (ValueError, RuntimeError):
            print("VPS Migrator: " + str(error), file=sys.stderr)
        else:
            print("VPS Migrator: операция прервана (" + type(error).__name__ +
                  "). Проверьте status и README для восстановления.", file=sys.stderr)
        sys.exit(1)
